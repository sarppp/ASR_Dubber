"""Reuse raw speech only when text, voice and synthesis settings match."""
import hashlib
import json
import shutil
import tempfile
from pathlib import Path


def file_digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def speech_key(text: str, settings: dict) -> str:
    data = json.dumps({"text": text, "settings": settings},
                      ensure_ascii=False, sort_keys=True).encode()
    return hashlib.sha256(data).hexdigest()


def restore(root: Path, key: str, destination: Path) -> bool:
    audio, meta = root / f"{key}.wav", root / f"{key}.json"
    try:
        if audio.stat().st_size <= 500 or file_digest(audio) != json.loads(
                meta.read_text())["sha256"]:
            return False
        shutil.copy2(audio, destination)
        return True
    except (OSError, ValueError, KeyError):
        return False


def save(root: Path, key: str, audio: Path) -> None:
    root.mkdir(parents=True, exist_ok=True)
    dest = root / f"{key}.wav"
    # Repeated lines can be generated by two workers concurrently. Unique
    # temporary names prevent one writer from moving another's staged file.
    with tempfile.TemporaryDirectory(dir=root) as directory:
        temp = Path(directory) / "audio.wav"
        shutil.copy2(audio, temp)
        meta = Path(directory) / "audio.json"
        meta.write_text(json.dumps({"sha256": file_digest(temp)}))
        temp.replace(dest)
        meta.replace(root / f"{key}.json")
